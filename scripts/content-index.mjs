// Turns the files in content/ into one TypeScript module the site imports.
//
// Content lives as plain files so anyone can fix a card or a story with a pull
// request and no build tooling. The site runs on Cloudflare Workers, which has
// no filesystem at runtime, so the files are folded into a module at build time.
// Run automatically by `npm run dev`, `build` and `deploy`.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "src/generated/content.ts");

const cards = readdirSync(join(root, "content/replace"))
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => {
    const c = JSON.parse(readFileSync(join(root, "content/replace", f), "utf8"));
    return { ...c, file: `content/replace/${f}` };
  });

function frontmatter(md) {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(md);
  if (!m) throw new Error("story is missing frontmatter");
  const meta = {}; const sources = []; let cur = null;
  for (const line of m[1].split("\n")) {
    const s = /^sources:\s*$/.exec(line); if (s) { cur = "sources"; continue; }
    const item = /^\s+-\s+label:\s*(.+)$/.exec(line); if (item) { sources.push({ label: item[1].trim(), url: "" }); continue; }
    const url = /^\s+url:\s*(.+)$/.exec(line); if (url && sources.length) { sources[sources.length - 1].url = url[1].trim(); continue; }
    const kv = /^([a-zA-Z]+):\s*(.*)$/.exec(line); if (kv) { cur = null; meta[kv[1]] = kv[2].replace(/^"(.*)"$/, "$1"); }
  }
  return { ...meta, sources, body: m[2].trim() };
}

const stories = readdirSync(join(root, "content/now"))
  .filter((f) => f.endsWith(".md"))
  .map((f) => ({ slug: f.replace(/\.md$/, ""), file: `content/now/${f}`, ...frontmatter(readFileSync(join(root, "content/now", f), "utf8")) }))
  .sort((a, b) => (a.date < b.date ? 1 : -1));

for (const c of cards) for (const k of ["slug", "title", "verdict", "oneLine", "why", "tool", "sources", "verified"]) if (c[k] === undefined) throw new Error(`${c.file} is missing "${k}"`);
for (const c of cards) if (!["yes", "partly", "no"].includes(c.verdict)) throw new Error(`${c.file}: verdict must be yes, partly or no`);
for (const s of stories) for (const k of ["title", "date", "summary"]) if (!s[k]) throw new Error(`${s.file} is missing "${k}"`);

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(out, `// GENERATED by scripts/content-index.mjs from content/. Do not edit; edit the files in content/.
import type { ReplaceCard, Story } from "@/lib/content";
export const REPLACE_CARDS: ReplaceCard[] = ${JSON.stringify(cards, null, 2)};
export const NOW_STORIES: Story[] = ${JSON.stringify(stories, null, 2)};
`);
console.log(`content index: ${cards.length} cards, ${stories.length} stories`);
